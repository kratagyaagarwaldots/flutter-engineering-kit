REGISTRY = json.loads((KIT / "install/harnesses.json").read_text())
HARNESSES = {h["id"]: h for h in REGISTRY["harnesses"]}
ROLES = json.loads((KIT / "install/roles.json").read_text())
HOME = pathlib.Path(os.environ.get("HOME", str(pathlib.Path.home())))
STATE = pathlib.Path(os.environ.get("FLUTTER_KIT_HOME", str(HOME / ".flutter-kit")))
BUILD = STATE / "build"
RECORD = STATE / "installed.json"
MODELS = STATE / "models.json"
EFFORTS = {"low", "medium", "high", "xhigh", "max", "ultra"}
