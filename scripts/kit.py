def models_discover() -> int:
    """What this machine can reach, without spending anything: installed harnesses, which
    provider keys are set (names only), and the model list from any CLI that prints one."""
    out = {"harnesses": {}, "keys_set": [k for k in KEY_VARS if os.environ.get(k)],
           "roles": {r: s["needs"] for r, s in ROLES["roles"].items()},
           "current": load_models()}
    for hid in detect():
        h = HARNESSES[hid]
        info = {"cli": next((shutil.which(b) for b in h["detect"]["bins"] if shutil.which(b)), None),
                "headless_verified": bool(h["headless"].get("verified")),
                "agent_model_values": h.get("agent_model_values")}
        if hid == "opencode" and info["cli"]:
            r = subprocess.run([info["cli"], "models"], capture_output=True, text=True, timeout=60)
            info["models"] = r.stdout.split() if r.returncode == 0 else None
        out["harnesses"][hid] = info
    print(json.dumps(out, indent=2))
    return 0


def headless_argv(hid: str, model: str, prompt: str, profile: str, budget: float,
                  effort: str | None = None) -> list[str]:
    t = HARNESSES[hid]["headless"]
    subs = {"{prompt}": prompt, "{model}": model, "{budget}": f"{budget:g}", "{effort}": effort or ""}

    def fill(a: str) -> str:
        for k, v in subs.items():
            a = a.replace(k, v)
        return a
    return ([fill(a) for a in t["argv"]] + ([fill(a) for a in t["effort"]] if effort else [])
            + list(t[profile]) + [fill(a) for a in t["tail"]])


def parse_run(hid: str, stdout: str) -> dict:
    """The run's text, its cost when the harness reports one, and which models answered."""
    t, data = HARNESSES[hid]["headless"], None
    for line in reversed([ln for ln in stdout.strip().splitlines() if ln.strip()] or [""]):
        try:
            data = json.loads(line)
            break
        except json.JSONDecodeError:
            continue
    if data is None:
        try:
            data = json.loads(stdout)
        except json.JSONDecodeError:
            return {"text": stdout, "cost": None, "models": []}
    if not isinstance(data, dict):
        return {"text": stdout, "cost": None, "models": []}
    cost = data.get(t["cost_field"]) if t.get("cost_field") else None
    used = list((data.get(t["models_field"]) or {}).keys()) if t.get("models_field") else []
    text = data.get(t["result_field"]) if t.get("result_field") else None
    return {"text": text if isinstance(text, str) else stdout, "cost": cost, "models": used}


def models_probe(hid: str, model: str, effort: str | None) -> int:
    """Spend a fraction of a cent to prove a model id works through this harness headless,
    and that the model which answered is the one asked for."""
    if hid not in HARNESSES:
        raise SystemExit(f"unknown harness '{hid}'")
    # Not a tiny cap: a cold headless start loads the harness's whole system prompt, which alone
    # can cost several cents. The probe reports what it really spent.
    argv = headless_argv(hid, model, "Reply with the single word: ok", "read", 0.5, effort)
    if not shutil.which(argv[0]):
        print(json.dumps({"ok": False, "error": f"{argv[0]} is not installed"}))
        return 1
    try:
        r = subprocess.run(argv, capture_output=True, text=True, timeout=180)
    except subprocess.TimeoutExpired:
        print(json.dumps({"ok": False, "error": "timed out after 180s"}))
        return 1
    run = parse_run(hid, r.stdout)
    ok = r.returncode == 0 and "ok" in (run["text"] or "").lower()
    print(json.dumps({"ok": ok, "harness": hid, "model": model, "answered_by": run["models"],
                      "cost_usd": run["cost"], "exit": r.returncode,
                      "output": (run["text"] or r.stderr)[-600:]}, indent=2))
    return 0 if ok else 1


def models_set(src: pathlib.Path) -> int:
    m = read_json(src, None)
    errs = check_models(m)
    if errs:
        print("models.json refused:")
        for e in errs:
            print(f"  - {e}")
        return 1
    m.setdefault("configured", __import__("datetime").date.today().isoformat())
    write_json(MODELS, m)
    print(f"saved {MODELS}")
    installed = [h for h in load_record()["harnesses"] if h in HARNESSES]
    if installed:
        install(installed)
    return 0


def models_report() -> int:
    """The loop's cost ledger, by role and model: what configure-models revisits."""
    rows: dict[tuple, dict] = {}
    for f in sorted((STATE / "loop").glob("*/runs.jsonl")):
        for line in f.read_text().splitlines():
            try:
                r = json.loads(line)
            except json.JSONDecodeError:
                continue
            k = (r.get("role"), r.get("harness"), r.get("model"))
            a = rows.setdefault(k, {"runs": 0, "cost": 0.0, "unknown_cost": 0, "failed": 0, "secs": 0})
            a["runs"] += 1
            a["secs"] += r.get("secs", 0)
            a["failed"] += 0 if r.get("ok") else 1
            if r.get("cost_known"):
                a["cost"] += r.get("cost", 0) or 0
            else:
                a["unknown_cost"] += 1
    if not rows:
        print("No loop runs recorded yet.")
        return 0
    print(f"{'role':<10}{'harness':<12}{'model':<34}{'runs':>5}{'failed':>8}{'cost $':>9}{'avg s':>7}")
    for (role, hid, model), a in sorted(rows.items(), key=lambda kv: str(kv[0])):
        cost = f"{a['cost']:.2f}" + ("+?" if a["unknown_cost"] else "")
        print(f"{str(role):<10}{str(hid):<12}{str(model)[:33]:<34}{a['runs']:>5}{a['failed']:>8}"
              f"{cost:>9}{a['secs'] // max(a['runs'], 1):>7}")
    return 0


