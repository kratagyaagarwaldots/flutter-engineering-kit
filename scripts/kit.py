GENERATED = "<!-- Generated by flutter-engineering-kit (scripts/kit.py). Re-run `kit install` instead of editing. -->"


# ---------------------------------------------------------------- helpers

def expand(p: str) -> pathlib.Path:
    return HOME / p[2:] if p.startswith("~/") else pathlib.Path(p)


def kit_ref() -> pathlib.Path:
    """The path installed files point at. Through ~/.flutter-kit/current when this run comes
    from there, so `kit update` re-points one symlink instead of rewriting every hook."""
    current = STATE / "current"
    if current.is_symlink() and current.resolve() == KIT:
        return current
    return KIT


def frontmatter(text: str) -> tuple[str, str]:
    m = re.match(r"^---\n(.*?)\n---\n?(.*)$", text, re.S)
    return (m.group(1), m.group(2)) if m else ("", text)


def field(front: str, key: str) -> str:
    m = re.search(rf"^{key}:\s*(.+)$", front, re.M)
    return m.group(1).strip().strip('"') if m else ""


def skills() -> list[pathlib.Path]:
    return sorted(p.parent for p in (KIT / "skills").glob("*/SKILL.md"))


def user_invoked() -> list[str]:
    return [d.name for d in skills()
            if "disable-model-invocation: true" in frontmatter((d / "SKILL.md").read_text())[0]]


def agents() -> list[pathlib.Path]:
    return sorted(p for p in (KIT / "agents").glob("*.md") if p.name != "README.md")


def read_json(path: pathlib.Path, default):
    if not path.exists():
        return default
    try:
        return json.loads(path.read_text())
    except json.JSONDecodeError:
        return json.loads(strip_jsonc(path.read_text()))


def write_json(path: pathlib.Path, data) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2) + "\n")


def strip_jsonc(text: str) -> str:
    out, i, n, in_str, esc = [], 0, len(text), False, False
    while i < n:
        c = text[i]
        if in_str:
            out.append(c)
            esc = (not esc) and c == "\\"
            if c == '"' and not esc:
                in_str = False
            i += 1
        elif c == '"':
            in_str = True
            out.append(c)
            i += 1
        elif text.startswith("//", i):
            while i < n and text[i] != "\n":
                i += 1
        elif text.startswith("/*", i):
            end = text.find("*/", i + 2)
            i = n if end < 0 else end + 2
        else:
            out.append(c)
            i += 1
    return "".join(out)


def link(src: pathlib.Path, dest: pathlib.Path, written: list[str]) -> None:
    """Symlink dest -> src. Refuses to replace anything that is not already our link."""
    dest.parent.mkdir(parents=True, exist_ok=True)
    if dest.is_symlink():
        dest.unlink()
    elif dest.exists():
        print(f"  skip {dest}: exists and is not the kit's link; leaving it alone", file=sys.stderr)
        return
    dest.symlink_to(src)
    written.append(str(dest))


def write_file(dest: pathlib.Path, text: str, written: list[str]) -> None:
    dest.parent.mkdir(parents=True, exist_ok=True)
    if dest.exists() and not dest.is_symlink() and GENERATED not in dest.read_text() \
            and "flutter-engineering-kit" not in dest.read_text():
        print(f"  skip {dest}: exists and was not written by the kit", file=sys.stderr)
        return
    if dest.is_symlink():
        dest.unlink()
    dest.write_text(text)
    written.append(str(dest))


def hook_cmd(harness: str, check: str) -> str:
    return f'python3 "{kit_ref() / "hooks" / HOOK_MARK}" {harness} {check}'


# ---------------------------------------------------------------- build

def build_skills() -> pathlib.Path:
    """Copy every skill into the build, adding Codex's agents/openai.yaml to the user-invoked
    ones. Codex ignores disable-model-invocation; this policy is how it keeps them manual."""
    out = BUILD / "skills"
    if out.exists():
        shutil.rmtree(out)
    manual = set(user_invoked())
    for d in skills():
        shutil.copytree(d, out / d.name)
        if d.name in manual:
            desc = field(frontmatter((d / "SKILL.md").read_text())[0], "description")
            (out / d.name / "agents").mkdir(exist_ok=True)
            (out / d.name / "agents" / "openai.yaml").write_text(
                "interface:\n"
                f"  display_name: {json.dumps(d.name)}\n"
                f"  short_description: {json.dumps(desc[:120])}\n"
                "policy:\n"
                "  allow_implicit_invocation: false\n")
    return out


def toml_str(s: str) -> str:
    return json.dumps(s)  # a JSON string is a valid TOML basic string


def convert_agent(src: pathlib.Path, fmt: str, pin: dict | None = None) -> tuple[str, str]:
    """`pin` is this agent's role entry for this harness from models.json. Without one the
    agent inherits the session's model, which is how a cheap job ends up on a frontier model."""
    front, body = frontmatter(src.read_text())
    name, desc = field(front, "name") or src.stem, field(front, "description")
    readonly = not re.search(r"Write|Edit", field(front, "tools"))
    body = body.strip() + "\n"
    model, effort = (pin or {}).get("model"), (pin or {}).get("effort")
    if fmt == "codex-toml":
        lines = [f"name = {toml_str(name)}", f"description = {toml_str(desc)}"]
        if model:
            lines.append(f"model = {toml_str(model)}")
        if effort:
            lines.append(f"model_reasoning_effort = {toml_str(effort)}")
        if readonly:
            lines.append('sandbox_mode = "read-only"')
        lines.append(f"developer_instructions = {toml_str(body)}")
        return f"{name}.toml", "# " + GENERATED.strip("<!-> ") + "\n" + "\n".join(lines) + "\n"
    if fmt == "opencode-md":
        head = ["---", f"description: {desc}", "mode: subagent"]
        if model:
            head.append(f"model: {model}")
        if readonly:
            head += ["permission:", "  edit: deny"]
    elif fmt == "antigravity-md":
        head = ["---", f"name: {name}", f"description: {desc}", f"model: {model or 'inherit'}"]
    else:  # cursor-md
        head = ["---", f"name: {name}", f"description: {desc}"]
        if model:
            head.append(f"model: {model}")
        if readonly:
            head.append("readonly: true")
    return f"{name}.md", "\n".join(head + ["---", "", GENERATED, "", body])


# ---------------------------------------------------------------- models

def role_of(agent: str) -> str | None:
    return next((r for r, spec in ROLES["roles"].items() if agent in spec["agents"]), None)


def load_models() -> dict | None:
    return read_json(MODELS, None)


def pin_for(agent: str, hid: str, models: dict | None) -> dict | None:
    if not models:
        return None
    return (models.get("roles", {}).get(role_of(agent) or "", {}) or {}).get(hid)


def check_models(m) -> list[str]:
    """Every way a models.json can be wrong, so `kit models set` refuses it before anything is
    pinned. Model ids themselves are not checked here: `kit models probe` does that by running one."""
    errs = []
    if not isinstance(m, dict) or m.get("version") != 1:
        return ["models.json needs \"version\": 1"]
    for role, per in (m.get("roles") or {}).items():
        if role not in ROLES["roles"]:
            errs.append(f"unknown role '{role}' (roles: {', '.join(ROLES['roles'])})")
            continue
        for hid, pin in (per or {}).items():
            if hid not in HARNESSES:
                errs.append(f"roles.{role}: unknown harness '{hid}'")
            elif not isinstance(pin, dict) or not str(pin.get("model", "")).strip():
                errs.append(f"roles.{role}.{hid}: needs a \"model\"")
            else:
                allowed = HARNESSES[hid].get("agent_model_values")
                if allowed and pin["model"] not in allowed:
                    errs.append(f"roles.{role}.{hid}: {HARNESSES[hid]['name']} agents take only "
                                f"{', '.join(allowed)}")
                if pin.get("effort") and pin["effort"] not in EFFORTS:
                    errs.append(f"roles.{role}.{hid}: effort '{pin['effort']}' is not one of "
                                f"{', '.join(sorted(EFFORTS))}")
    loop = m.get("loop") or {}
    for key, spec in loop.items():
        if key not in ROLES["loop"] or key.startswith("$"):
            errs.append(f"unknown loop role '{key}' (loop roles: "
                        f"{', '.join(k for k in ROLES['loop'] if not k.startswith('$'))})")
            continue
        hid = (spec or {}).get("harness")
        if hid not in HARNESSES:
            errs.append(f"loop.{key}: unknown harness '{hid}'")
            continue
        ladder = spec.get("ladder")
        if not isinstance(ladder, list) or not ladder:
            errs.append(f"loop.{key}: needs a non-empty \"ladder\" of models, cheapest first")
        if not HARNESSES[hid]["headless"].get("verified") and not m.get("allow_unverified"):
            errs.append(f"loop.{key}: {HARNESSES[hid]['name']}'s headless run is unverified; probe it "
                        f"with `kit models probe {hid} <model>` and set \"allow_unverified\": true")
    b, r = loop.get("builder", {}), loop.get("reviewer", {})
    if b and r and b.get("ladder") and r.get("ladder") and b["ladder"][0] == r["ladder"][0]:
        errs.append("loop: the reviewer starts on the builder's model; pick another family so the "
                    "two do not share blind spots")
    budget = m.get("budget", {})
    for k, v in budget.items():
        if not isinstance(v, (int, float)) or v <= 0:
            errs.append(f"budget.{k}: must be a positive number of dollars")
    if isinstance(budget.get("per_run_usd"), (int, float)) and 0 < budget["per_run_usd"] < 0.25:
        errs.append("budget.per_run_usd: under $0.25 a run can be stopped by its own cold start, "
                    "which loads the harness's whole system prompt before any work")
    return errs


def models_show() -> int:
    m = load_models()
    if not m:
        print("No models configured: kit sub-agents inherit whatever model the session runs.\n"
              "Ask your agent to configure them (the configure-models skill).")
        return 1
    print(f"configured {m.get('configured', '?')}" + (f" · {m['basis']}" if m.get("basis") else ""))
    for role, spec in ROLES["roles"].items():
        per = m.get("roles", {}).get(role, {})
        cells = [f"{h}={p['model']}" + (f"({p['effort']})" if p.get("effort") else "")
                 for h, p in per.items()]
        print(f"  {role:<8} {', '.join(cells) or 'inherits'}   [{', '.join(spec['agents']) or 'loop only'}]")
    for key, spec in (m.get("loop") or {}).items():
        print(f"  loop.{key:<10} {spec['harness']}: {' → '.join(str(s) for s in spec['ladder'])}")
    if m.get("budget"):
        print("  budget   " + ", ".join(f"{k}=${v}" for k, v in m["budget"].items()))
    return 0


